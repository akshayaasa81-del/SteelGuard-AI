from pathlib import Path
import numpy as np
from PIL import Image
import torch
import torch.nn as nn
from torchvision import models, transforms
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import normalize

IMAGE_SIZE = 224

def get_transform():
    return transforms.Compose([
        transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
        transforms.Grayscale(num_output_channels=3),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406],
                             std=[0.229, 0.224, 0.225]),
    ])

def build_backbone(device):
    # Uses ImageNet pretrained weights when available in the local cache / internet.
    try:
        weights = models.ResNet18_Weights.DEFAULT
        net = models.resnet18(weights=weights)
    except Exception:
        net = models.resnet18(weights=None)
    net.fc = nn.Identity()
    net.eval()
    net.to(device)
    for p in net.parameters():
        p.requires_grad = False
    return net

@torch.inference_mode()
def get_embedding(model, image, device):
    if not isinstance(image, Image.Image):
        image = Image.open(image).convert("RGB")
    tensor = get_transform()(image.convert("RGB")).unsqueeze(0).to(device)
    emb = model(tensor).detach().cpu().numpy()[0].astype(np.float32)
    norm = np.linalg.norm(emb) + 1e-12
    return emb / norm

def fit_prototypes(embeddings, labels, class_names):
    prototypes = {}
    for name in class_names:
        vecs = embeddings[np.array(labels) == name]
        if len(vecs):
            p = vecs.mean(axis=0)
            p = p / (np.linalg.norm(p) + 1e-12)
            prototypes[name] = p.astype(np.float32)
    return prototypes

def cosine_distance(a, b):
    a = a / (np.linalg.norm(a) + 1e-12)
    b = b / (np.linalg.norm(b) + 1e-12)
    return float(1.0 - np.dot(a, b))

def predict_image(model, image, known_classes, prototypes, threshold, device,
                  new_prototype=None, new_class_name=None):
    emb = get_embedding(model, image, device)
    logits = model._steelguard_classifier.predict_proba(emb.reshape(1, -1))[0]
    class_names = model._steelguard_classifier.classes_
    best_idx = int(np.argmax(logits))
    nearest_known = str(class_names[best_idx])
    confidence = float(logits[best_idx])

    distances = {name: cosine_distance(emb, proto) for name, proto in prototypes.items()}
    nearest_name = min(distances, key=distances.get)
    nearest_distance = distances[nearest_name]

    # If an operator-added class exists, compare it too. It is accepted only if closer
    # than both the known-class distance and the same calibrated threshold.
    if new_prototype is not None and new_class_name:
        new_dist = cosine_distance(emb, new_prototype)
        if new_dist <= threshold and new_dist < nearest_distance:
            return {"status": "learned", "class_name": new_class_name,
                    "confidence": confidence, "distance": new_dist,
                    "nearest_known": nearest_name}

    if nearest_distance > threshold:
        return {"status": "unknown", "class_name": "unknown",
                "confidence": confidence, "distance": nearest_distance,
                "nearest_known": nearest_name}
    return {"status": "known", "class_name": nearest_name,
            "confidence": confidence, "distance": nearest_distance,
            "nearest_known": nearest_name}

def add_few_shot_class(model, images, device):
    embs = np.stack([get_embedding(model, img, device) for img in images])
    proto = embs.mean(axis=0)
    proto = proto / (np.linalg.norm(proto) + 1e-12)
    return proto.astype(np.float32)

def load_bundle(path):
    # Bundle contains a serialized model object; only load artifacts generated by your own script.
    bundle = torch.load(path, map_location="cpu", weights_only=False)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = bundle["backbone"].to(device).eval()
    model._steelguard_classifier = bundle["classifier"]
    return {
        "model": model,
        "known_classes": bundle["known_classes"],
        "held_out_class": bundle["held_out_class"],
        "prototypes": bundle["prototypes"],
        "unknown_threshold": bundle["unknown_threshold"],
        "device": device
    }


def prepare_image(image):
    """Convert an uploaded PIL image into the model's expected tensor."""
    transform = get_transform()
    return transform(image.convert("RGB"))


def evaluate_unknown_detection(
    model,
    images,
    known_classes,
    prototypes,
    threshold,
    device
):
    """Evaluate predictions and flag images beyond the distance threshold."""
    results = []

    for image in images:
        embedding = get_embedding(model, image, device)

        distances = {
            label: cosine_distance(embedding, prototype)
            for label, prototype in prototypes.items()
            if label in known_classes
        }

        if not distances:
            results.append({
                "prediction": "Unknown",
                "distance": None
            })
            continue

        nearest_class = min(distances, key=distances.get)
        nearest_distance = distances[nearest_class]

        prediction = (
            "Unknown"
            if nearest_distance > threshold
            else nearest_class
        )

        results.append({
            "prediction": prediction,
            "nearest_class": nearest_class,
            "distance": float(nearest_distance)
        })

    return results

